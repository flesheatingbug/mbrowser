// Preload for the browser's own chrome (toolbar, tab bar, overlay)
const { contextBridge, ipcRenderer } = require('electron');

const send = (ch) => (...a) => ipcRenderer.send(ch, ...a);

contextBridge.exposeInMainWorld('api', {
  newTab: send('tab:new'),
  switchTab: send('tab:switch'),
  closeTab: send('tab:close'),
  tabMenu: send('tab:menu'),
  moveTab: send('tab:move'),
  dragEnd: send('tab:dragend'),
  muteTab: send('tab:mute'),
  mainMenu: send('menu:main'),
  profileMenu: send('profile:menu'),
  showSecurity: send('security:show'),
  pwAction: (a) => ipcRenderer.invoke('pw:action', a),
  showLogins: send('logins:show'),
  panelToggle: send('panel:toggle'),
  panelResize: send('panel:resize'),
  tabList: send('tablist:show'),
  tablistSwitch: send('tablist:switch'),
  tablistClose: send('tablist:close'),
  tablistReopen: send('tablist:reopen'),
  onTablistData: (cb) => ipcRenderer.on('tablist:data', (_e, d) => cb(d)),
  winMin: send('win:min'),
  winMax: send('win:max'),
  winClose: send('win:close'),
  suggestQuery: send('suggest:query'),
  suggestNav: send('suggest:nav'),
  suggestClose: send('suggest:close'),
  urlEnter: send('url:enter'),
  onUrlFill: (cb) => ipcRenderer.on('url:fill', (_e, t) => cb(t)),
  onSuggestItems: (cb) => ipcRenderer.on('suggest:items', (_e, items, sel) => cb(items, sel)),
  resetZoom: send('zoom:reset'),
  go: send('nav:go'),
  back: send('nav:back'),
  forward: send('nav:forward'),
  reload: send('nav:reload'),
  toggleBookmark: send('bookmark:toggle'),
  toggleShield: send('shield:toggle'),
  closeOverlay: send('overlay:close'),
  find: send('find:do'),
  paletteQuery: (q) => ipcRenderer.invoke('palette:query', q),
  paletteRun: send('palette:run'),
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  onFocusUrl: (cb) => ipcRenderer.on('focus-url', () => cb()),
  onOverlayOpen: (cb) => ipcRenderer.on('overlay:open', (_e, mode, data) => cb(mode, data)),
  onFindResult: (cb) => ipcRenderer.on('find:result', (_e, r) => cb(r)),
});
