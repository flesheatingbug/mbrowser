// Preload for the browser's own chrome (toolbar, tab bar, overlay)
const { contextBridge, ipcRenderer } = require('electron');

const send = (ch) => (...a) => ipcRenderer.send(ch, ...a);

contextBridge.exposeInMainWorld('api', {
  newTab: (url) => ipcRenderer.send('tab:new', url),
  switchTab: send('tab:switch'),
  closeTab: send('tab:close'),
  tabMenu: send('tab:menu'),
  moveTab: send('tab:move'),
  dragEnd: send('tab:dragend'),
  muteTab: send('tab:mute'),
  nextTab: send('tab:next'),
  prevTab: send('tab:prev'),
  translatePage: send('translate:page'),
  translateDismiss: send('translate:dismiss'),
  defaultBarSet: send('defaultbar:set'),
  defaultBarClose: send('defaultbar:close'),
  defaultBarNever: send('defaultbar:never'),
  activeTabClick: send('tab:active-click'),
  newPrivateTab: send('tab:new-private'),
  mainMenu: send('menu:main'),
  profileMenu: send('profile:menu'),
  showSecurity: send('security:show'),
  pwAction: (a) => ipcRenderer.invoke('pw:action', a),
  showLogins: send('logins:show'),
  panelToggle: send('panel:toggle'),
  panelResize: send('panel:resize'),
  tabList: send('tablist:show'),
  tablistSwitch: send('tablist:switch'),
  tablistClose: send('tablist:close'),
  tablistReopen: send('tablist:reopen'),
  onTablistData: (cb) => ipcRenderer.on('tablist:data', (_e, d) => cb(d)),
  lockNow: send('lock:now'),
  homeToggle: send('home:toggle'),
  extClick: send('ext:click'),
  extMenu: send('ext:menu'),
  lockInfo: () => ipcRenderer.invoke('lock:info'),
  lockUnlock: (pw) => ipcRenderer.invoke('lock:unlock', pw),
  onLockShown: (cb) => ipcRenderer.on('lock:shown', () => cb()),
  winMin: send('win:min'),
  winMax: send('win:max'),
  winClose: send('win:close'),
  suggestQuery: send('suggest:query'),
  suggestNav: send('suggest:nav'),
  suggestForget: send('suggest:forget'),
  suggestClose: send('suggest:close'),
  urlEnter: send('url:enter'),
  onUrlFill: (cb) => ipcRenderer.on('url:fill', (_e, t) => cb(t)),
  onSuggestItems: (cb) => ipcRenderer.on('suggest:items', (_e, items, sel) => cb(items, sel)),
  resetZoom: send('zoom:reset'),
  setZoom: send('zoom:set'),
  go: send('nav:go'),
  urlMenu: (hasSel) => ipcRenderer.send('url:menu', !!hasSel),
  back: send('nav:back'),
  forward: send('nav:forward'),
  reload: send('nav:reload'),
  toggleBookmark: send('bookmark:toggle'),
  toggleShield: send('shield:toggle'),
  allowHost: send('shield:allowHost'),
  closeOverlay: send('overlay:close'),
  find: send('find:do'),
  paletteQuery: (q) => ipcRenderer.invoke('palette:query', q),
  paletteRun: send('palette:run'),
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  onFocusUrl: (cb) => ipcRenderer.on('focus-url', () => cb()),
  downloadAction: (id, action) => ipcRenderer.invoke('downloads:action', id, action),
  engineMenu: () => ipcRenderer.send('engine:menu'),
  newtabMenu: () => ipcRenderer.send('tab:newtab-menu'),
  openDownloads: () => ipcRenderer.send('tab:new', 'my://downloads'),
  showDlCtxMenu: (id) => ipcRenderer.send('downloads:ctxmenu', id),
  onOverlayOpen: (cb) => ipcRenderer.on('overlay:open', (_e, mode, data) => cb(mode, data)),
  onFindResult: (cb) => ipcRenderer.on('find:result', (_e, r) => cb(r)),
  onUpdateAvailable: (cb) => ipcRenderer.on('app:update-available', (_e, info) => cb(info)),
  onUpdateDownloading: (cb) => ipcRenderer.on('app:update-downloading', (_e, pct) => cb(pct)),
  onUpdateReady: (cb) => ipcRenderer.on('app:update-ready', (_e, info) => cb(info)),
  blockerStatus: () => ipcRenderer.invoke('blocker:status'),
  blockerUpdate: () => ipcRenderer.invoke('blocker:update'),
  checkUpdates: () => ipcRenderer.invoke('app:check-updates'),
  installUpdate: (info) => ipcRenderer.invoke('app:install-update', info),
  invoke: (ch, ...a) => ipcRenderer.invoke(ch, ...a),
});
